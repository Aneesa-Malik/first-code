SELECT I.INS_ID, I.INS_NAME, COUNT(C.CO_ID) AS TOTAL_COURSES
FROM INSTRUCTOR I
JOIN COURSE C ON I.INS_ID = C.INS_ID
GROUP BY I.INS_ID, I.INS_NAME
HAVING COUNT(C.CO_ID) > 1;

