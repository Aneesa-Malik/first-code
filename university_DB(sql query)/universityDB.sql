CREATE TABLE STUDENT (
ST_ID NUMBER PRIMARY KEY,
ST_NAME VARCHAR2(50) NOT NULL,
EMAIL VARCHAR2(100) UNIQUE,
GPA NUMBER(3,2) CHECK (GPA BETWEEN 0 AND 4)
); 
SELECT *FROM STUDENT;
CREATE TABLE INSTRUCTOR (
INS_ID NUMBER PRIMARY KEY,
INS_NAME VARCHAR2(50) NOT NULL,
EMAIL VARCHAR2(100) UNIQUE
);
SELECT *FROM INSTRUCTOR; 

CREATE TABLE COURSE (
CO_ID NUMBER PRIMARY KEY,
CO_NAME VARCHAR2(50) NOT NULL,
CO_HOURS NUMBER CHECK (CO_HOURS > 0),
INS_ID NUMBER,
FOREIGN KEY (INS_ID) REFERENCES INSTRUCTOR(INS_ID)
);
SELECT *FROM COURSE;

CREATE TABLE ENROLLMENT (
EN_ID NUMBER PRIMARY KEY,
ST_ID NUMBER NOT NULL,
CO_ID NUMBER NOT NULL,
GRADE VARCHAR2(2),
FOREIGN KEY (ST_ID) REFERENCES STUDENT(ST_ID),
FOREIGN KEY (CO_ID) REFERENCES COURSE(CO_ID)
);
